from django.urls import path

from .views import (
    JobListView,
    JobDetailView,
    JobCreateView,
    JobUpdateView,
    JobDeleteView,
    apply_job,
    MyApplicationListView,
    MyJobsListView,
    JobApplicantsListView,
    update_application_status,
    resume_analyzer,
)

urlpatterns = [
    path("", JobListView.as_view(), name="job-list"),
    path(
        "job/<int:pk>/",
        JobDetailView.as_view(),
        name="job-detail",
    ),
    path(
        "job/create/",
        JobCreateView.as_view(),
        name="job-create",
    ),
    path(
        "job/<int:pk>/update/",
        JobUpdateView.as_view(),
        name="job-update",
    ),
    path(
        "job/<int:pk>/delete/",
        JobDeleteView.as_view(),
        name="job-delete",
    ),
    path(
        "job/<int:pk>/apply/",
        apply_job,
        name="apply-job",
    ),
    path(
        "my-applications/",
        MyApplicationListView.as_view(),
        name="my-applications",
    ),
    path(
        "my-jobs/",
        MyJobsListView.as_view(),
        name="my-jobs",
    ),
    path(
        "job/<int:pk>/applicants/",
        JobApplicantsListView.as_view(),
        name="job-applicants",
    ),
    path(
        "application/<int:pk>/status/",
        update_application_status,
        name="update-application-status",
    ),
    path(
        "resume-analyzer/",
        resume_analyzer,
        name="resume-analyzer",
    ),
]
